/**
 * Copies contracts/deployments/31337.json → packages/sdk/deployments/
 * and writes apps/api/.env.local for the on-chain oracle keeper.
 *
 * Usage (from repo root): node scripts/sync-deployment.mjs
 *
 * Expects JSON from `script/Deploy.sol:Deploy` (AccessManager + role holders).
 */

import { copyFileSync, mkdirSync, readFileSync, writeFileSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const src = join(root, "contracts/deployments/31337.json");

if (!existsSync(src)) {
  console.error("Missing", src, ": run forge script script/Deploy.sol:Deploy first.");
  process.exit(1);
}

const deployment = JSON.parse(readFileSync(src, "utf8"));
const sdkDir = join(root, "packages/sdk/deployments");
mkdirSync(sdkDir, { recursive: true });
copyFileSync(src, join(sdkDir, "31337.json"));

const anvilKey =
  "0xac0974bec39a17e36ba4a6b4d238ff944bacb478cbed5efcae784d7bf4f2ff80";

const attestorKey =
  "0x2a871d0798f97d79848a013d4936a73bf4cc922c825d33c1cf7073dff6d409c6";

const envLocal = `# Generated by scripts/sync-deployment.mjs - local Anvil adapter
PORT=4000
HOST=0.0.0.0
ORACLE_RPC_URL=http://127.0.0.1:8545
ORACLE_CHAIN_ID=${deployment.chainId ?? 31337}
COMPLIANCE_ORACLE_ADDRESS=${deployment.ComplianceOracle}
AML_HOOK_ADDRESS=${deployment.AmlHook ?? ""}
SANCTION_REGISTRY_ADDRESS=${deployment.SanctionRegistry ?? ""}
FEE_ESCROW_ADDRESS=${deployment.FeeEscrow ?? ""}
FEE_TOKEN_ADDRESS=${deployment.feeToken ?? ""}
WETH_TOKEN_ADDRESS=${deployment.wethToken ?? ""}
USD_FEED_ADDRESS=${deployment.usdFeed ?? ""}
ETH_USD_FEED_ADDRESS=${deployment.ethUsdFeed ?? ""}
COMPLIANCE_TREASURY_ADDRESS=${deployment.ComplianceTreasury ?? ""}
COMPLIANCE_RESERVE=${deployment.ComplianceTreasury ?? deployment.complianceReserve ?? ""}
LP_COMPENSATION_FUND=${deployment.lpCompensationFund ?? deployment.LpCompensationVault ?? ""}
LP_COMPENSATION_VAULT=${deployment.LpCompensationVault ?? deployment.lpCompensationFund ?? ""}
COMPENSATION_LPS=${deployment.admin ?? ""}
KEEPER_PRIVATE_KEY=${anvilKey}
ATTESTOR_PRIVATE_KEY=${attestorKey}
SCORE_SOURCE=onchain
# AccessManager=${deployment.AccessManager ?? ""}
# attestor=${deployment.attestor ?? ""}: Anvil #9 on the local chain
# oracleKeeper=${deployment.oracleKeeper ?? deployment.keeper ?? ""}: must hold _ORACLE_KEEPER
`;

writeFileSync(join(root, "apps/api/.env.local"), envLocal);

console.log("Synced SDK deployments/31337.json");
console.log("Wrote apps/api/.env.local");
if (deployment.AccessManager) {
  console.log("AccessManager", deployment.AccessManager);
}
console.log(JSON.stringify(deployment, null, 2));
