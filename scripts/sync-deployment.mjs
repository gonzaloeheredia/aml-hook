/**
 * Copies contracts/deployments/31337.json → packages/sdk/deployments/
 * and writes apps/api/.env.local for the on-chain keeper.
 *
 * Usage (from repo root): node scripts/sync-deployment.mjs
 */

import { copyFileSync, mkdirSync, readFileSync, writeFileSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const src = join(root, "contracts/deployments/31337.json");

if (!existsSync(src)) {
  console.error("Missing", src, "— run forge script DeployAmlStack first.");
  process.exit(1);
}

const deployment = JSON.parse(readFileSync(src, "utf8"));
const sdkDir = join(root, "packages/sdk/deployments");
mkdirSync(sdkDir, { recursive: true });
copyFileSync(src, join(sdkDir, "31337.json"));

const anvilKey =
  "0xac0974bec39a17e36ba4a6b4d238ff944bacb478cbed5efcae784d7bf4f2ff80";

const envLocal = `# Generated by scripts/sync-deployment.mjs - local Anvil keeper
PORT=4000
HOST=0.0.0.0
ORACLE_RPC_URL=http://127.0.0.1:8545
ORACLE_CHAIN_ID=${deployment.chainId ?? 31337}
COMPLIANCE_ORACLE_ADDRESS=${deployment.ComplianceOracle}
KEEPER_PRIVATE_KEY=${anvilKey}
SCORE_SOURCE=onchain
`;

writeFileSync(join(root, "apps/api/.env.local"), envLocal);

console.log("Synced SDK deployments/31337.json");
console.log("Wrote apps/api/.env.local");
console.log(JSON.stringify(deployment, null, 2));
